const LanguageContext = createContext(null)
export function LanguageProvider({ children }) {
  const [language, setLanguageState] = useState(() => ['pt','en','es'].includes(localStorage.getItem('lembracar.language')) ? localStorage.getItem('lembracar.language') : 'pt')
  useEffect(() => { document.documentElement.lang = language === 'pt' ? 'pt-BR' : language }, [language])
  const setLanguage = (value) => { setLanguageState(value); localStorage.setItem('lembracar.language', value); document.documentElement.lang = value === 'pt' ? 'pt-BR' : value }
  const t = (text) => messages[language]?.[text] || text
  const value = useMemo(() => ({ language, setLanguage, t, locale: language === 'pt' ? 'pt-BR' : language === 'es' ? 'es-ES' : 'en-US' }), [language])
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}
export function useLanguage() { return useContext(LanguageContext) }
